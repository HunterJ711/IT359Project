"""Generate deterministic Markdown reports from normalized scan evidence."""

from __future__ import annotations

from collections import Counter

from .models import Finding, ScanResult


def _safe(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def render_markdown_report(
    scan: ScanResult,
    findings: list[Finding],
    *,
    ai_requested: bool = False,
    ai_model: str = "",
    ai_warnings: list[str] | None = None,
) -> str:
    """Return a complete Markdown report.

    The report explicitly identifies deterministic rule output and optional
    AI-enhanced guidance without allowing AI to overwrite scan evidence.
    """

    counts = Counter(item.severity for item in findings)
    lines = [
        "# APTriage Penetration Testing Analysis",
        "",
        "> **Authorized use only.** This report analyzes supplied Nmap evidence. "
        "It does not prove exploitation or replace manual validation.",
        "",
        "## Executive Summary",
        "",
        f"APTriage parsed **{len(scan.hosts)} host(s)** and **{scan.open_service_count} open service(s)** "
        f"from `{_safe(scan.source_file)}`. The deterministic rules produced "
        f"**{len(findings)} finding(s)**: **{counts['High']} High**, "
        f"**{counts['Medium']} Medium**, and **{counts['Low']} Low**.",
        "",
        "## Scan Metadata",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Scanner | {_safe(scan.scanner)} {_safe(scan.scanner_version)} |",
        f"| Original command | `{_safe(scan.command_line) or 'Not recorded'}` |",
        f"| Scan started | {_safe(scan.started_at) or 'Not recorded'} |",
        f"| Scan finished | {_safe(scan.finished_at) or 'Not recorded'} |",
        f"| Parsed at | {_safe(scan.parsed_at)} |",
        "",
        "## Host and Service Inventory",
        "",
    ]

    if not scan.hosts:
        lines.extend(["No hosts were present in the supplied Nmap XML.", ""])

    for host in scan.hosts:
        lines.extend(
            [
                f"### Host `{_safe(host.address)}`",
                "",
                f"- **Status:** {_safe(host.status)}",
                f"- **Hostnames:** {', '.join(map(_safe, host.hostnames)) or 'None reported'}",
                f"- **OS guesses:** {', '.join(map(_safe, host.os_matches)) or 'None reported'}",
                "",
                "| Port | Protocol | State | Service |",
                "|---:|---|---|---|",
            ]
        )
        if host.services:
            for service in host.services:
                lines.append(
                    f"| {service.port} | {_safe(service.protocol)} | {_safe(service.state)} | "
                    f"{_safe(service.display_name)} |"
                )
        else:
            lines.append("| — | — | — | No open services reported |")
        lines.append("")

    lines.extend(["## Findings", ""])
    if not findings:
        lines.extend(["No open-service findings were produced.", ""])

    for index, finding in enumerate(findings, start=1):
        lines.extend(
            [
                f"### {index}. {finding.title}",
                "",
                f"- **Severity:** {finding.severity}",
                f"- **Rule:** `{finding.rule_id}`",
                f"- **Host:** `{_safe(finding.host)}`",
                f"- **Service:** `{finding.port}/{_safe(finding.protocol)}` — {_safe(finding.service)}",
                "",
                "**Evidence**",
                "",
                finding.evidence,
                "",
                "**Why it matters**",
                "",
                finding.rationale,
                "",
                "**Recommendation**",
                "",
                finding.recommendation,
                "",
                f"**Analysis source:** {_safe(finding.analysis_source)}. Manual validation required.",
                "",
            ]
        )

    enhanced_count = sum(item.analysis_source.startswith("Sushi AI") for item in findings)
    warnings = ai_warnings or []
    if ai_requested:
        ai_status = (
            f"Sushi AI enhancement was requested using `{_safe(ai_model)}`. "
            f"**{enhanced_count} of {len(findings)} finding(s)** were enhanced. "
            "Severity and scan evidence remained controlled by deterministic APTriage rules."
        )
        if warnings:
            ai_status += " The remaining findings used deterministic fallback guidance."
    else:
        ai_status = (
            "AI enhancement was not enabled for this report. All findings and recommendations above "
            "were generated by transparent, deterministic rules."
        )

    lines.extend(
        [
            "## Limitations",
            "",
            "- Nmap service detection can be incomplete or inaccurate.",
            "- An open port does not by itself prove a vulnerability or missing authentication.",
            "- Severity reflects exposure-based triage rules, not CVSS scoring.",
            "- This report does not include exploitation or credential testing.",
            "- Findings should be validated by an authorized security professional.",
            "",
            "## AI Analysis Status",
            "",
            ai_status,
            "",
        ]
    )
    if warnings:
        lines.extend(["### AI Fallback Notes", ""])
        lines.extend(f"- {_safe(item)}" for item in warnings)
        lines.append("")
    return "\n".join(lines)

